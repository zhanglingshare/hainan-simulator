"use strict";
const {chromium}=require("playwright");
const assert=require("node:assert/strict");
(async()=>{
 const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
 let errors=[];
 try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  page.on("pageerror",e=>errors.push(e.message));
  const response=await page.goto("http://127.0.0.1:8765/industry/",{waitUntil:"networkidle"});
  assert.equal(response.status(),200,"research page must load");
  await page.locator("#historyPanel").waitFor();
  assert.equal(await page.locator("#signalCards button").count(),4,"four real-world signal cards");
  await page.locator("[data-signal='1']").click();
  assert.match(await page.locator("#signalTitle").innerText(),/进出口/);
  await page.locator("[data-nav=network]").click();
  assert.equal(await page.locator("#networkSvg [data-node]").count(),8);
  await page.locator("#networkSvg [data-node=services]").click();
  assert.match(await page.locator("#nodeTitle").innerText(),/专业服务/);
  await page.locator("[data-nav=lab]").click();
  await page.locator("#scenarioValue").waitFor();
  const before=await page.locator("#scenarioValue").innerText();
  await page.locator("#rate1").evaluate(el=>{el.value="8";el.dispatchEvent(new Event("input",{bubbles:true}));});
  const after=await page.locator("#scenarioValue").innerText();
  assert.notEqual(before,after,"changing directly assumed industrial growth updates forecast accounting");
  await page.locator("#breakLink").selectOption("port-service");
  const unchanged=await page.locator("#scenarioValue").innerText();
  assert.equal(after,unchanged,"hypothetical network break must NEVER change GDP");
  await page.locator("#localShare").evaluate(el=>{el.value="85";el.dispatchEvent(new Event("input",{bubbles:true}));});
  assert.match(await page.locator("#localResult").innerText(),/85\.0/);
  assert.equal(await page.locator("#scenarioValue").innerText(),unchanged,"local procurement assumption must not enter GDP");
  await page.locator("#saveExperiment").click();
  await page.locator("[data-nav=archive]").click();
  assert.ok(await page.locator("[data-load]").count()>=1,"archive has saved experiments");
  await page.locator("[data-load]").first().click();
  assert.equal(await page.locator("#lab").isVisible(),true,"saved case restores to lab");
  await page.locator("[data-nav=blindspots]").click();
  assert.equal(await page.locator("#challengeGrid button").count(),4);
  await page.locator("[data-challenge='2']").click();
  await page.locator("#applyChallenge").click();
  assert.equal(await page.locator("#lab").isVisible(),true);
  const phone=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:2,hasTouch:true});
  phone.on("pageerror",e=>errors.push("mobile: "+e.message));
  await phone.goto("http://127.0.0.1:8765/industry/#discover",{waitUntil:"networkidle"});
  assert.equal(await phone.locator("#discover").isVisible(),true);
  await phone.locator("[data-nav=lab]").click();
  assert.equal(await phone.locator("#lab").isVisible(),true);
  const width=await phone.evaluate(()=>document.documentElement.scrollWidth);
  assert.ok(width<=415,"mobile view should not have significant horizontal overflow: "+width);
  assert.deepEqual(errors,[],"no uncaught browser JS errors");
  console.log("BROWSER SMOKE SUCCESS: desktop navigation, observed signals, SVG network, live rate, no GDP leakage, archive, red-team, mobile responsive");
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});